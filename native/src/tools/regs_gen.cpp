#include <popcorn/arch/armv8m/armv8m.hpp>
#include <popcorn/core/description.hpp>

#include <algorithm>
#include <cctype>
#include <fstream>
#include <iterator>
#include <print>
#include <string>
#include <string_view>
#include <utility>
#include <vector>

namespace
{
auto upper(std::string_view name) -> std::string
{
  std::string out;
  for(auto const c : name)
  {
    out.push_back(static_cast<char>(std::toupper(static_cast<unsigned char>(c))));
  }
  return out;
}
}

auto main(int argc, char** argv) -> int
{
  if(argc != 2)
  {
    std::println(stderr, "usage: popcorn-regs-gen <output _regs.py>");
    return 2;
  }
  auto const profile = [](std::string cpu, bool fpu, bool fpu_double, bool trustzone) {
    return popcorn::core_desc{
        .cpu                   = std::move(cpu),
        .revision              = "r0p1",
        .fpu                   = fpu,
        .fpu_double            = fpu_double,
        .mpu                   = true,
        .mpu_regions           = 8,
        .mpu_regions_secure    = 0,
        .sau_regions           = 0,
        .trustzone             = trustzone,
        .dsp                   = true,
        .nvic_prio_bits        = 3,
        .num_irqs              = 1,
        .vendor_systick_config = false,
        .reset_clock_hz        = 1,
    };
  };
  std::vector<popcorn::arch::cpu_register> registers;
  for(auto const& core :
      {profile("CM33", true, false, true), profile("CM4", true, false, false),
       profile("CM7", true, true, false), profile("CM3", false, false, false)})
  {
    if(not popcorn::arch::armv8m::implements(core))
    {
      std::println(stderr, "popcorn-regs-gen: the Cortex-M module does not implement {}", core.cpu);
      return 1;
    }
    for(auto const& reg : popcorn::arch::armv8m::factory()(core)->registers())
    {
      if(std::ranges::find(registers, reg.name, &popcorn::arch::cpu_register::name)
         == registers.end())
      {
        registers.push_back(reg);
      }
    }
  }
  std::ranges::copy(popcorn::arch::armv8m::trustzone_registers(), std::back_inserter(registers));

  std::ofstream out{argv[1]};
  std::println(
      out, "\"\"\"Registers of the Arm M-profile cores, generated by popcorn-regs-gen.\"\"\"");
  std::println(out);
  std::println(out, "import enum");
  std::println(out);
  std::println(out, "from popcorn._views import RegisterBank");
  std::println(out);
  std::println(out);
  std::println(out, "class Reg(enum.Enum):");
  std::println(out, "    \"\"\"A core register, valued by its name in the arch module.\"\"\"");
  std::println(out);
  for(auto const& reg : registers)
  {
    std::println(out, "    {} = \"{}\"", upper(reg.name), reg.name);
  }
  std::println(out);
  std::println(out);
  std::println(out, "class Registers(RegisterBank[Reg]):");
  std::println(
      out, "    \"\"\"Core registers as typed attributes. A core without an FPU has no s0-s31, "
           "fpscr. Only a machine with TrustZone enabled has secure and the _s and _ns "
           "registers.\"\"\"");
  for(auto const& reg : registers)
  {
    std::println(out);
    std::println(out, "    @property");
    std::println(out, "    def {}(self) -> int:", reg.name);
    std::println(out, "        \"\"\"Register {}, {} bits.\"\"\"", reg.name, reg.bits);
    std::println(out, "        return self[Reg.{}]", upper(reg.name));
    std::println(out);
    std::println(out, "    @{}.setter", reg.name);
    std::println(out, "    def {}(self, value: int) -> None:", reg.name);
    std::println(out, "        self[Reg.{}] = value", upper(reg.name));
  }
  return out.good() ? 0 : 1;
}
