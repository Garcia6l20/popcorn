import re
import shutil
import subprocess
import sys
from pathlib import Path

from pcons import PackageDescription
from pcons.packages.fetch.cli import fetch_package, load_deps_file

from popcorn_build.config import build_dir, project_dir

PACKAGE = project_dir / "build" / "popcorn" / "__init__.py"
GENERATED = project_dir / "docs" / "support" / "generated"
SDK_API = project_dir / "docs" / "reference" / "sdk" / "api"
DOXYFILE = project_dir / "popcorn_build" / "sdk_docs" / "Doxyfile"
THEME = "doxygen-awesome-css"
THEME_STYLESHEETS = ("doxygen-awesome.css", "doxygen-awesome-sidebar-only.css")

STUB = """<!doctype html>
<meta charset="utf-8">
<title>Plugin SDK API</title>
<p>The C++ API reference is generated by doxygen, which was not installed when these pages were
built. Install doxygen and run <code>uv run python -m popcorn_build.docs</code> again.</p>
"""

_ANSI = re.compile(r"\x1b\[[0-9;]*m")


def build_command() -> list[str]:
    """The strict Zensical build. `--strict` fails it on a broken link or anchor, and a missing
    snippet or reference object fails it on its own. griffe's docstring warnings do not fail
    it, `flagged()` catches those."""
    return [
        sys.executable,
        "-m",
        "zensical",
        "build",
        "--strict",
        "--config-file",
        str(project_dir / "zensical.toml"),
    ]


def flagged(line: str) -> bool:
    """Whether a line of the build output is a warning the docs stage fails on."""
    plain = _ANSI.sub("", line)
    return plain.startswith("griffe:") or "WARNING" in plain.upper()


def generate() -> int:
    """Regenerate the support pages into docs/support/generated, in an interpreter of its own so
    only the built-in models count. The return code of that interpreter."""
    shutil.rmtree(GENERATED, ignore_errors=True)
    return subprocess.run(
        [sys.executable, "-m", "popcorn_build.support_pages", str(GENERATED)],
        cwd=project_dir,
        check=False,
    ).returncode


def theme_stylesheets() -> list[Path] | None:
    """The doxygen-awesome-css stylesheets of the SDK reference, fetched from deps.toml into the
    build directory on first use. None, after one warning, when the fetch fails or a file is
    missing: the reference then keeps doxygen's default style."""
    deps = build_dir / "deps"
    packages = build_dir / "pkg"
    description = packages / f"{THEME}.pcons-pkg.toml"
    if not description.exists():
        manifest = load_deps_file(project_dir / "deps.toml")["packages"]
        if not fetch_package(THEME, manifest[THEME], deps, packages):
            print(
                f"popcorn docs: fetching {THEME} failed,"
                " the SDK API reference uses the default style",
                file=sys.stderr,
            )
            return None
    prefix = Path(PackageDescription.from_toml(description).prefix)
    files = [prefix / name for name in THEME_STYLESHEETS]
    if not all(file.is_file() for file in files):
        print(
            f"popcorn docs: {THEME} files are missing,"
            " the SDK API reference uses the default style",
            file=sys.stderr,
        )
        return None
    return files


def build_sdk_reference(output: Path = SDK_API) -> int:
    """Generate the C++ plugin SDK reference with doxygen into `output`, the HTML files of the
    SDK header set. Without doxygen on PATH, print one warning and write a stub page so the links
    to it resolve. The return code is 1 when doxygen reports a warning, an undocumented public
    declaration included."""
    shutil.rmtree(output, ignore_errors=True)
    output.mkdir(parents=True)
    if shutil.which("doxygen") is None:
        print("popcorn docs: doxygen not found, the SDK API reference is a stub", file=sys.stderr)
        (output / "index.html").write_text(STUB)
        return 0
    config = DOXYFILE.read_text() + f"\nOUTPUT_DIRECTORY = {output}\n"
    theme = theme_stylesheets()
    if theme is not None:
        config += f"HTML_EXTRA_STYLESHEET = {' '.join(str(file) for file in theme)}\n"
    done = subprocess.run(["doxygen", "-"], input=config, text=True, cwd=project_dir, check=False)
    return done.returncode


def run() -> int:
    """Generate the support pages, run the build, stream its output, and return 1 on a warning
    line or a failed step.

    mkdocstrings and the support pages read the package from build/popcorn, so the native build
    comes first."""
    if not PACKAGE.is_file():
        print(
            f"popcorn docs: {PACKAGE.parent} is missing, run `uv run pcons -B build` first",
            file=sys.stderr,
        )
        return 1
    generated = generate()
    if generated != 0:
        return generated
    sdk = build_sdk_reference()
    if sdk != 0:
        return sdk
    warnings: list[str] = []
    with subprocess.Popen(
        build_command(),
        cwd=project_dir,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    ) as build:
        assert build.stdout is not None
        for line in build.stdout:
            sys.stdout.write(line)
            if flagged(line):
                warnings.append(line.rstrip())
    if build.returncode != 0:
        return build.returncode
    if warnings:
        print(f"popcorn docs: {len(warnings)} warning line(s) fail the build", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(run())
